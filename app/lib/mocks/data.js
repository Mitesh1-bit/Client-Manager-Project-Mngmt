const DAY = 24 * 60 * 60 * 1000;
const anchor = new Date();
anchor.setHours(9, 0, 0, 0);

/** @param {number} days */
function iso(days) {
  return new Date(anchor.getTime() + days * DAY).toISOString();
}

/** @param {number} days */
function day(days) {
  return iso(days).slice(0, 10);
}

