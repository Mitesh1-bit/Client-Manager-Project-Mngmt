const { Kind, print, visit } = require("graphql");

function collectFragmentNames(node, fragments, found = new Set()) {
  visit(node, {
    FragmentSpread(spread) {
      const name = spread.name.value;
      if (found.has(name)) return;
      found.add(name);
      const definition = fragments.get(name);
      if (definition) collectFragmentNames(definition, fragments, found);
    },
  });
  return found;
}

/**
 * Emits plain-JS `DocumentNode` constants (no TypeScript) from the project's
 * .graphql operations. Codegen validates every document against schema.graphql
 * before this runs, so an unknown field fails the build rather than production.
 */
module.exports.plugin = (_schema, documents) => {
  const fragments = new Map();
  const operations = [];

  for (const file of documents) {
    for (const definition of file.document.definitions) {
      if (definition.kind === Kind.FRAGMENT_DEFINITION) {
        fragments.set(definition.name.value, definition);
      } else if (definition.kind === Kind.OPERATION_DEFINITION) {
        if (!definition.name) {
          throw new Error(`Anonymous operation in ${file.location} — every document must be named.`);
        }
        operations.push(definition);
      }
    }
  }

  const blocks = [];

  for (const [name, definition] of [...fragments].sort(([a], [b]) => a.localeCompare(b))) {
    const dependencies = [...collectFragmentNames(definition, fragments)]
      .filter((dependency) => dependency !== name)
      .sort();
    const source = [definition, ...dependencies.map((d) => fragments.get(d))]
      .filter(Boolean)
      .map(print)
      .join("\n");
    blocks.push(`export const ${name}FragmentDoc = gql\`\n${source}\`;`);
  }

  for (const operation of [...operations].sort((a, b) =>
    a.name.value.localeCompare(b.name.value),
  )) {
    const dependencies = [...collectFragmentNames(operation, fragments)].sort();
    const source = [operation, ...dependencies.map((d) => fragments.get(d))]
      .filter(Boolean)
      .map(print)
      .join("\n");
    blocks.push(`export const ${operation.name.value}Document = gql\`\n${source}\`;`);
  }

  return [
    "// Generated by GraphQL Code Generator from schema.graphql. Do not edit by hand.",
    "// Run `npm run codegen` after changing any .graphql document.",
    "",
    'import { gql } from "@apollo/client";',
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
};
